const captures=[...document.querySelectorAll('.work-capture')];
if(captures.length!==6)throw Error('需要六张截图');
const repoLinks=[...document.querySelectorAll('.project-links a')].filter(a=>a.href.startsWith('https://github.com/JackZhong1998/'));
if(repoLinks.length!==3)throw Error('需要三个项目代码链接');
document.querySelector('[data-gallery="剪辑 Agent"]').click();
const shown=captures.filter(f=>!f.hidden);
if(shown.length!==2||shown.some(f=>f.dataset.group!=='剪辑 Agent'))throw Error('图片分组错误');
shown[0].querySelector('button').click();
const modal=document.getElementById('image-viewer');
if(!modal.open)throw Error('大图未打开');
let pic=[...modal.querySelectorAll('img')].find(im=>!im.hidden);
await pic.decode();
if(!pic.getAttribute('src').includes('agent-entry'))throw Error('打开错误图片');
document.getElementById('viewer-next').click();
pic=[...modal.querySelectorAll('img')].find(im=>!im.hidden);
await pic.decode();
if(!pic.getAttribute('src').includes('agent-skill'))throw Error('下一张错误');
document.getElementById('viewer-close').click();
await new Promise(resolve=>setTimeout(resolve,100));
if(modal.open||document.body.style.overflow==='hidden')throw Error('关闭失败');
document.getElementById('work-gallery').scrollIntoView({behavior:'instant',block:'center'});
return {passed:true,captures:captures.length,repositories:repoLinks.length,category:'剪辑 Agent',largeImageNavigation:true};